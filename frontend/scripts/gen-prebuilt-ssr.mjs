// Regenerates functions/_lib/prebuilt-screens.js from src/app5.js.
// Run after changing PREBUILT_SCREENS or METRICS:  node scripts/gen-prebuilt-ssr.mjs
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = fs.readFileSync(path.join(root, 'src/app5.js'), 'utf8')

const METRICS = eval('(' + src.match(/const METRICS = \{[\s\S]*?\n\}/)[0].replace('const METRICS = ', '') + ')')
const SCREENS = eval('(' + src.match(/const PREBUILT_SCREENS = \[[\s\S]*?\n\]/)[0].replace('const PREBUILT_SCREENS = ', '') + ')')

const norm = v => String(v || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
const lookup = {}
for (const [n, d] of Object.entries(METRICS)) lookup[norm(n)] = { key: d.key, string: !!d.string }
const slugify = n => n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')

const out = SCREENS.map(s => {
  const conditions = []
  for (const part of s.q.split(/\s+AND\s+/i)) {
    const m = part.trim().match(/^(.+?)\s*(>=|<=|>|<|=)\s*(.+)/)
    const e = lookup[norm(m[1])]
    let v = m[3].trim()
    if (!e.string) {
      v = Number(v.replace(/[$,%]/g, ''))
      if (e.key === 'marketCap') v = v * 1e6
    }
    conditions.push({ metric: e.key, op: m[2], value: v })
  }
  return { slug: slugify(s.name), name: s.name, cat: s.cat, desc: s.desc, q: s.q, conditions }
})

const parserSource = `export function parseQuerySSR(q) {
  const norm = v => String(v || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
  const conditions = []
  for (const part of String(q || '').split(/\\s+AND\\s+/i)) {
    const m = part.trim().match(/^(.+?)\\s*(>=|<=|>|<|=)\\s*(.+)$/)
    if (!m) continue
    const entry = METRICS_SSR[norm(m[1])]
    if (!entry) continue
    let value = m[3].trim()
    if (!entry.string) {
      value = Number(value.replace(/[$,%]/g, ''))
      if (!Number.isFinite(value)) continue
      if (entry.key === 'marketCap') value = value * 1e6
    } else {
      value = value.replace(/^["']|["']$/g, '').trim()
      if (!value) continue
    }
    conditions.push({ metric: entry.key, op: m[2], value })
  }
  return conditions
}
`

let file = '// AUTO-GENERATED by scripts/gen-prebuilt-ssr.mjs from src/app5.js — do not edit by hand.\n'
file += '// Used by [[catchall]].js to server-render /screeners/* pages for SEO.\n'
file += 'export const PREBUILT_SCREENS_SSR = ' + JSON.stringify(out, null, 1) + '\n\n'
file += 'export const METRICS_SSR = ' + JSON.stringify(lookup, null, 1) + '\n\n'
file += parserSource

fs.writeFileSync(path.join(root, 'functions/_lib/prebuilt-screens.js'), file)
console.log('wrote', out.length, 'screens +', Object.keys(lookup).length, 'metrics')
