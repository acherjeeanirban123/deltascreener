/**
 * D1-compatible adapter backed by PostgreSQL.
 *
 * The Cloudflare Worker (worker-d1-upload.js) talks to D1 through a small API:
 *     env.DB.prepare(sql).bind(...params).run() / .all() / .first()
 *     env.DB.batch([stmt, stmt, ...])
 *
 * This module reimplements that exact surface on top of node-postgres, so the
 * 8000-line worker file needs ZERO changes. It also translates SQLite dialect
 * (what D1 speaks) into Postgres dialect on the fly — see translate() below.
 */

import pg from 'pg'

const { Pool } = pg

// ─────────────────────────────────────────────────────────────────────────────
// Type fidelity with D1
//
// node-postgres returns BIGINT (int8) and NUMERIC as *strings* to avoid
// precision loss. D1/SQLite returned real numbers, so without this the API
// would emit  {"total":"2000"}  where production emits  {"total":2000}  —
// which silently breaks any arithmetic or strict comparison in the frontend.
//
// int8 values here are row counts and market caps (max ~1e13), far below
// Number.MAX_SAFE_INTEGER (9e15), so Number() is lossless in practice.
// A guard is kept for anything that would actually lose precision.
// ─────────────────────────────────────────────────────────────────────────────
const INT8 = 20, NUMERIC = 1700, FLOAT8 = 701, FLOAT4 = 700

pg.types.setTypeParser(INT8, v => {
  if (v === null) return null
  const n = Number(v)
  return Number.isSafeInteger(n) ? n : v   // keep as string if truly huge
})
pg.types.setTypeParser(NUMERIC, v => (v === null ? null : Number(v)))
pg.types.setTypeParser(FLOAT8, v => (v === null ? null : Number(v)))
pg.types.setTypeParser(FLOAT4, v => (v === null ? null : Number(v)))

// ─────────────────────────────────────────────────────────────────────────────
// SQL dialect translation: SQLite (D1) → PostgreSQL
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Convert `?` positional placeholders to Postgres `$1, $2, ...`.
 * Skips `?` that appear inside single-quoted string literals.
 */
function convertPlaceholders(sql) {
  let out = ''
  let i = 0
  let n = 0
  let inString = false
  while (i < sql.length) {
    const ch = sql[i]
    if (ch === "'") {
      // Handle escaped '' inside strings
      if (inString && sql[i + 1] === "'") { out += "''"; i += 2; continue }
      inString = !inString
      out += ch
      i++
      continue
    }
    if (ch === '?' && !inString) {
      out += '$' + (++n)
      i++
      continue
    }
    out += ch
    i++
  }
  return out
}

/**
 * Rewrite SQLite-specific syntax/functions into Postgres equivalents.
 * Only the constructs actually used by worker-d1-upload.js are handled.
 */
function translate(sql) {
  let s = sql

  // ── PRAGMA table_info(t) → information_schema ────────────────────────────
  // ensureStockSchema() introspects columns this way to decide which ALTERs to
  // run. Postgres has no PRAGMA, so map it to an equivalent shape ({ name }).
  const pragma = s.match(/^\s*PRAGMA\s+table_info\(\s*['"]?(\w+)['"]?\s*\)\s*;?\s*$/i)
  if (pragma) {
    return `SELECT column_name AS name, data_type AS type
            FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = '${pragma[1]}'
            ORDER BY ordinal_position`
  }

  // ── DDL ──────────────────────────────────────────────────────────────────
  // INTEGER PRIMARY KEY AUTOINCREMENT → GENERATED ALWAYS AS IDENTITY
  s = s.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi,
    'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  // SQLite REAL → Postgres DOUBLE PRECISION
  s = s.replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
  // ALTER TABLE ... ADD COLUMN → make idempotent (worker relies on .catch())
  s = s.replace(/ALTER\s+TABLE\s+(\S+)\s+ADD\s+COLUMN\s+/gi,
    'ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ')

  // ── Date/time ────────────────────────────────────────────────────────────
  // datetime('now') → now() as text (columns are TEXT in the original schema)
  s = s.replace(/datetime\(\s*'now'\s*\)/gi, "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"')")
  // datetime(x) used for comparison → cast to timestamptz
  s = s.replace(/datetime\(\s*([^)]+?)\s*\)/gi, '(($1)::timestamptz)')

  // ── JSON ─────────────────────────────────────────────────────────────────
  // json_extract(col, '$.a.b')  → col::jsonb #>> '{a,b}'
  s = s.replace(/json_extract\(\s*([^,]+?)\s*,\s*'\$\.([^']+)'\s*\)/gi, (_m, col, path) => {
    const parts = path.split('.').map(p => p.trim()).filter(Boolean)
    return `((${col})::jsonb #>> '{${parts.join(',')}}')`
  })
  // json_extract(col, '$')      → whole document
  s = s.replace(/json_extract\(\s*([^,]+?)\s*,\s*'\$'\s*\)/gi, '(($1)::jsonb)')
  // json_each(x) → jsonb_array_elements((x)::jsonb) AS json_each(value)
  //
  // SQLite exposes json_each as a virtual TABLE, so the worker's queries say
  //     FROM json_each(...) WHERE json_each.value IS NOT NULL
  // Postgres has a set-returning function instead, which produces no such
  // table name. Aliasing the result `AS json_each(value)` keeps every
  // `json_each.value` reference in the original SQL valid and untouched.
  //
  // The ::jsonb cast is required because json_extract() above translates to
  // `#>>` (which returns text); jsonb_array_elements needs real jsonb.
  s = replaceJsonEach(s)

  // ── Misc functions ───────────────────────────────────────────────────────
  // SQLite's IFNULL is Postgres COALESCE
  s = s.replace(/\bIFNULL\(/gi, 'COALESCE(')

  // LIKE → ILIKE.
  // SQLite's LIKE is case-INSENSITIVE for ASCII; Postgres's is case-SENSITIVE.
  // Left unfixed, /search?q=apple finds nothing for "Apple Inc." — it silently
  // returns fewer results rather than erroring, so it is easy to miss.
  // NOT LIKE is handled by the same substitution (NOT ILIKE stays valid).
  s = s.replace(/\bLIKE\b/gi, 'ILIKE')
  // Integer division guard: SQLite `/` on ints truncates like Postgres — no change needed.

  // ── Upsert ───────────────────────────────────────────────────────────────
  // `excluded.` is identical in Postgres, no change needed.

  return s
}

/**
 * Rewrite every `json_each(<expr>)` into
 *     jsonb_array_elements((<expr>)::jsonb) AS json_each(value)
 *
 * Done with a paren-matching scanner rather than a regex, because <expr> is
 * itself full of nested parentheses and quoted JSON paths.
 */
function replaceJsonEach(sql) {
  let out = sql
  let cursor = 0          // never rescan text we've already emitted —
  let guard = 0           // the replacement itself contains "json_each(value)"
  while (guard++ < 50) {
    const rest = out.slice(cursor)
    const m = /json_each\s*\(/i.exec(rest)
    if (!m) break
    m.index += cursor                           // shift back to absolute index
    const open = m.index + m[0].length - 1      // index of '('
    let depth = 0, inStr = false, close = -1
    for (let i = open; i < out.length; i++) {
      const c = out[i]
      if (inStr) {
        if (c === "'") { if (out[i + 1] === "'") { i++; continue } inStr = false }
        continue
      }
      if (c === "'") { inStr = true; continue }
      if (c === '(') depth++
      else if (c === ')') { depth--; if (depth === 0) { close = i; break } }
    }
    if (close < 0) break                        // unbalanced — leave as-is
    const inner = out.slice(open + 1, close)
    const replacement = `jsonb_array_elements((${inner})::jsonb) AS json_each(value)`
    out = out.slice(0, m.index) + replacement + out.slice(close + 1)
    cursor = m.index + replacement.length       // resume past what we inserted
  }
  return out
}

/** Convert D1's `{ results, meta }` shape from a pg result. */
function toD1Result(res) {
  return {
    results: res?.rows ?? [],
    success: true,
    meta: {
      changes: res?.rowCount ?? 0,
      rows_read: res?.rows?.length ?? 0,
      rows_written: res?.rowCount ?? 0,
      last_row_id: res?.rows?.[0]?.id ?? null
    }
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// Prepared statement — mirrors D1PreparedStatement
// ─────────────────────────────────────────────────────────────────────────────

class PreparedStatement {
  constructor(pool, sql, params = []) {
    this.pool = pool
    this.sql = sql
    this.params = params
  }

  bind(...params) {
    return new PreparedStatement(this.pool, this.sql, params)
  }

  async _exec(client) {
    const text = convertPlaceholders(translate(this.sql))
    const runner = client || this.pool
    try {
      return await runner.query(text, this.params)
    } catch (e) {
      // Surface the translated SQL — makes dialect bugs findable instead of silent.
      e.message = `${e.message}\n--- translated SQL ---\n${text}`
      throw e
    }
  }

  async run(client) {
    return toD1Result(await this._exec(client))
  }

  async all(client) {
    return toD1Result(await this._exec(client))
  }

  async first(colOrClient) {
    const res = await this._exec(typeof colOrClient === 'string' ? null : colOrClient)
    const row = res.rows?.[0]
    if (!row) return null
    if (typeof colOrClient === 'string') return row[colOrClient] ?? null
    return row
  }

  async raw(client) {
    const res = await this._exec(client)
    return (res.rows || []).map(r => Object.values(r))
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// Database handle — mirrors D1Database
// ─────────────────────────────────────────────────────────────────────────────

class PostgresD1 {
  constructor(pool) {
    this.pool = pool
  }

  prepare(sql) {
    return new PreparedStatement(this.pool, sql)
  }

  /**
   * D1's batch() runs all statements in a single implicit transaction.
   * We do the same with a dedicated client + BEGIN/COMMIT.
   */
  async batch(statements) {
    const client = await this.pool.connect()
    try {
      await client.query('BEGIN')
      const out = []
      for (const stmt of statements) {
        out.push(await stmt.run(client))
      }
      await client.query('COMMIT')
      return out
    } catch (e) {
      await client.query('ROLLBACK').catch(() => {})
      throw e
    } finally {
      client.release()
    }
  }

  /** D1 exec() — run raw SQL, semicolon-separated. */
  async exec(sql) {
    const res = await this.pool.query(translate(sql))
    return { count: Array.isArray(res) ? res.length : 1, duration: 0 }
  }

  async close() {
    await this.pool.end()
  }
}

/**
 * Create a D1-compatible database handle backed by Postgres.
 * @param {string} connectionString  e.g. postgres://user:pass@localhost:5432/deltascreener_db
 */
export function createD1(connectionString, opts = {}) {
  const pool = new Pool({
    connectionString,
    max: opts.max ?? 10,
    idleTimeoutMillis: opts.idleTimeoutMillis ?? 30_000,
    connectionTimeoutMillis: opts.connectionTimeoutMillis ?? 10_000
  })
  pool.on('error', err => console.error('[pg] idle client error:', err.message))
  return new PostgresD1(pool)
}

