/**
 * Unit tests for the SQLite→Postgres SQL translation layer.
 *
 * This is the single riskiest part of the port: if translation is wrong, queries
 * fail at runtime (or worse, silently return wrong data). Run it after any edit
 * to adapters/d1-postgres.js — it needs no database.
 *
 *   node migrate/test-translate.js
 */

import { translate, convertPlaceholders } from '../adapters/d1-postgres.js'

let pass = 0, fail = 0

function check(label, actual, expectSubstrings, notExpect = []) {
  const missing = expectSubstrings.filter(s => !actual.includes(s))
  const leaked = notExpect.filter(s => actual.includes(s))
  if (!missing.length && !leaked.length) { pass++; console.log(`  ✓ ${label}`); return }
  fail++
  console.log(`  ✗ ${label}`)
  if (missing.length) console.log(`      missing: ${JSON.stringify(missing)}`)
  if (leaked.length) console.log(`      should not contain: ${JSON.stringify(leaked)}`)
  console.log(`      got: ${actual.replace(/\s+/g, ' ').slice(0, 160)}`)
}

console.log('\nPlaceholders')
check('? → $1,$2',
  convertPlaceholders('SELECT * FROM t WHERE a=? AND b=?'),
  ['a=$1', 'b=$2'], ['?'])
check('? inside string literal is left alone',
  convertPlaceholders("SELECT * FROM t WHERE note='why?' AND id=?"),
  ["note='why?'", 'id=$1'])
check('escaped quote handled',
  convertPlaceholders("SELECT 'it''s' AS x WHERE id=?"),
  ["'it''s'", 'id=$1'])

console.log('\nDDL')
check('AUTOINCREMENT → IDENTITY',
  translate('CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, v REAL)'),
  ['GENERATED BY DEFAULT AS IDENTITY', 'DOUBLE PRECISION'], ['AUTOINCREMENT', ' REAL'])
check('ADD COLUMN made idempotent',
  translate('ALTER TABLE watchlists ADD COLUMN exchange TEXT'),
  ['ADD COLUMN IF NOT EXISTS'])

console.log('\nDate/time')
check("datetime('now') → to_char(now())",
  translate("INSERT INTO t (a) VALUES (datetime('now'))"),
  ['to_char(now()'], ["datetime('now')"])
check('datetime(col) → timestamptz cast',
  translate("SELECT * FROM t WHERE datetime(created_at) <= datetime(?)"),
  ['::timestamptz'])

console.log('\nJSON')
check("json_extract($.key) → #>>",
  translate("SELECT json_extract(overview, '$.description') FROM stock_data"),
  ['::jsonb #>>', "'{description}'"], ['json_extract'])
check('nested json path',
  translate("SELECT json_extract(v, '$.a.b.c') FROM t"),
  ["'{a,b,c}'"])
check('json_each → jsonb_array_elements with table alias',
  translate("SELECT * FROM json_each(COALESCE(json_extract(financials,'$.income'),'[]'))"),
  ['jsonb_array_elements', '::jsonb) AS json_each(value)'])

// Regression: SQLite exposes json_each as a virtual TABLE, so the worker
// references `json_each.value`. Without the alias this silently returned 0
// rows in Postgres, which showed up as screenableTickers=0 on /admin/status.
check('json_each.value reference stays valid (real STOCK_FINANCIAL_READY_SQL shape)',
  translate(`EXISTS (
    SELECT 1
    FROM json_each(COALESCE(json_extract((CASE WHEN d.financials IS NOT NULL AND d.financials<>'' THEN d.financials ELSE '{}' END), '$.income.revenue'), '[]'))
    WHERE json_each.value IS NOT NULL
      AND TRIM(CAST(json_each.value AS TEXT)) NOT IN ('', 'null')
  )`),
  ['jsonb_array_elements', 'AS json_each(value)', 'WHERE json_each.value IS NOT NULL'])

check('two json_each in one statement both rewritten',
  translate(`SELECT (SELECT COUNT(1) FROM json_each(json_extract(a,'$.x')) WHERE json_each.value IS NOT NULL),
                    (SELECT COUNT(1) FROM json_each(json_extract(b,'$.y')) WHERE json_each.value IS NOT NULL)`),
  ['jsonb_array_elements'], ['FROM json_each('])

console.log('\nCase sensitivity')
// SQLite LIKE is case-insensitive, Postgres LIKE is not. Without ILIKE,
// /search?q=apple silently returned 2 results instead of 4.
check('LIKE → ILIKE',
  translate("SELECT * FROM t WHERE u.ticker LIKE ? OR u.name LIKE ?"),
  ['ILIKE'], [' LIKE '])
check('NOT LIKE → NOT ILIKE',
  translate("SELECT * FROM t WHERE name NOT LIKE '%x%'"),
  ['NOT ILIKE'])

console.log('\nPRAGMA')
check('PRAGMA table_info → information_schema',
  translate('PRAGMA table_info(stock_data)'),
  ['information_schema.columns', "table_name = 'stock_data'", 'AS name'], ['PRAGMA'])

console.log('\nReal queries from worker-d1-upload.js')
check('coverage count JOIN',
  translate(`SELECT COUNT(*) AS count FROM stock_universe u JOIN stock_data d ON d.ticker=u.ticker
             WHERE u.is_active=1 AND d.overview IS NOT NULL AND d.overview NOT IN ('', '{}', 'null')`),
  ['COUNT(*)', 'JOIN stock_data'])
check('watchlist upsert',
  convertPlaceholders(translate(
    `INSERT INTO watchlists (user_id,ticker,name,price,exchange,"change",change_pct,updated_at)
     VALUES (?,?,?,?,?,?,?,datetime('now'))`)),
  ['$1', '$7', 'to_char(now()', '"change"'], ['?'])
check('app_meta lock upsert (json_extract + excluded)',
  convertPlaceholders(translate(
    `INSERT INTO app_meta (key,value) VALUES (?,?)
     ON CONFLICT(key) DO UPDATE SET value = CASE
       WHEN json_extract(app_meta.value, '$.lockedAt') IS NULL THEN excluded.value
       WHEN json_extract(app_meta.value, '$.version') != ? THEN excluded.value
       ELSE app_meta.value END`)),
  ['ON CONFLICT(key)', 'excluded.value', '::jsonb #>>', '$3'], ['json_extract', '?'])
check('description backfill predicate',
  translate(`SELECT ticker FROM stock_data WHERE
      json_extract(overview, '$.description') IS NULL
      OR TRIM(json_extract(overview, '$.description')) IN ('', '—')`),
  ['::jsonb #>>'], ['json_extract'])

console.log(fail === 0
  ? `\n✅ ${pass} translation tests passed.\n`
  : `\n❌ ${fail} failed, ${pass} passed.\n`)
process.exit(fail === 0 ? 0 : 1)
